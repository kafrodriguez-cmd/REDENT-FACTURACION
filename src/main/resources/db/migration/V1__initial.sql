CREATE TABLE app_user (
  username VARCHAR(80) PRIMARY KEY, password VARCHAR(200) NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','OPERADOR','CONSULTA')), enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE settings (name VARCHAR(80) PRIMARY KEY, json TEXT NOT NULL);
CREATE TABLE catalog (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind VARCHAR(20) NOT NULL CHECK (kind IN ('clientes','productos')),
  code VARCHAR(100) NOT NULL, name VARCHAR(250) NOT NULL, json TEXT NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE, revision INTEGER NOT NULL DEFAULT 0,
  UNIQUE(kind,code)
);
CREATE TABLE sequence_number (scope VARCHAR(80) PRIMARY KEY, last_number BIGINT NOT NULL);
CREATE TABLE document (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind VARCHAR(20) NOT NULL, status VARCHAR(30) NOT NULL,
  request_key VARCHAR(100) NOT NULL UNIQUE, request_hash VARCHAR(64) NOT NULL,
  input_json TEXT NOT NULL, json TEXT, generation VARCHAR(36) UNIQUE, control_number VARCHAR(40), fiscal_year INTEGER,
  UNIQUE(control_number,fiscal_year),
  signed_jws TEXT, response_json TEXT, seal VARCHAR(100),
  related_id BIGINT REFERENCES document(id), total DECIMAL(18,2) NOT NULL DEFAULT 0,
  created_by VARCHAR(80) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  revision INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_document_status ON document(status,created_at);
CREATE TABLE audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actor VARCHAR(80) NOT NULL, action VARCHAR(80) NOT NULL, entity VARCHAR(100) NOT NULL, detail VARCHAR(1000) NOT NULL
);
CREATE TABLE attempt (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id BIGINT NOT NULL REFERENCES document(id), operation VARCHAR(30) NOT NULL,
  started_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  finished_at TIMESTAMP WITH TIME ZONE, outcome VARCHAR(30), response_json TEXT
);
CREATE TABLE email_delivery (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, document_id BIGINT NOT NULL REFERENCES document(id),
 recipient VARCHAR(254) NOT NULL, status VARCHAR(30) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
